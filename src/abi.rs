//! C/C++ declarations generated from canonical checked types, with layout assertions.
use crate::{
    resolve::Index,
    syntax::ItemKind,
    types::{CheckedTypes, Ty},
};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
#[derive(Debug, Clone)]
pub struct Header {
    pub source: String,
    pub symbols: BTreeMap<String, String>,
}
pub fn identifier(name: &str) -> String {
    let mut result = String::from("fg_");
    for byte in name.bytes() {
        write!(result, "{byte:02x}").unwrap();
    }
    result
}
fn scalar(ty: &Ty) -> String {
    match ty {
        Ty::Integer { signed, bits } => format!("{}int{bits}_t", if *signed { "" } else { "u" }),
        Ty::Bool => "uint8_t".into(),
        Ty::Struct(id) | Ty::Enum(id) => identifier(id),
        _ => unreachable!(),
    }
}
pub(crate) fn declaration(ty: &Ty, name: &str) -> String {
    match ty {
        Ty::Pointer(inner) => declaration(
            inner,
            &if matches!(**inner, Ty::Array(..)) {
                format!("(*{name})")
            } else {
                format!("*{name}")
            },
        ),
        Ty::Array(inner, n) => declaration(inner, &format!("{name}[{n}]")),
        _ => format!("{} {name}", scalar(ty)),
    }
}
pub(crate) fn constant(value: i128) -> String {
    if value == i64::MIN as i128 {
        "(-INT64_C(9223372036854775807)-1)".into()
    } else if value < 0 {
        format!("(-INT64_C({}))", -value)
    } else {
        format!("UINT64_C({value})")
    }
}
fn value_dependencies(ty: &Ty, found: &mut BTreeSet<String>) {
    match ty {
        Ty::Struct(id) => {
            found.insert(id.clone());
        }
        Ty::Array(inner, _) => value_dependencies(inner, found),
        _ => {}
    }
}
pub fn generate(index: &Index, checked: &CheckedTypes) -> Result<Header, String> {
    let mut out = String::from(
        "/* Generated by Fingolfin. Linux x86-64 little-endian ABI. */\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n#if !defined(__linux__) || !defined(__x86_64__) || __BYTE_ORDER__ != __ORDER_LITTLE_ENDIAN__\n#error \"Unsupported Fingolfin ABI target\"\n#endif\n#ifdef __cplusplus\n#define FG_LAYOUT_ASSERT static_assert\n#define FG_LAYOUT_ALIGN alignof\nextern \"C\" {\n#else\n#define FG_LAYOUT_ASSERT _Static_assert\n#define FG_LAYOUT_ALIGN _Alignof\n#endif\n",
    );
    let symbols = index
        .symbols
        .iter()
        .filter(|(_, symbol)| !matches!(symbol.declaration.value.kind, ItemKind::Object { .. }))
        .map(|(id, _)| (id.clone(), identifier(id)))
        .collect();
    for (id, symbol) in &index.symbols {
        if matches!(symbol.declaration.value.kind, ItemKind::Struct { .. }) {
            let name = identifier(id);
            writeln!(out, "typedef struct {name} {name};").unwrap();
        }
    }
    for (id, symbol) in &index.symbols {
        if let ItemKind::Enum { repr, variants, .. } = &symbol.declaration.value.kind {
            let repr = crate::types::resolve_type(index, &symbol.module, repr)?;
            let name = identifier(id);
            writeln!(out, "typedef {} {name};", scalar(&repr)).unwrap();
            for variant in variants {
                writeln!(
                    out,
                    "#define {} (({name}){})",
                    identifier(&format!("{id}::{}", variant.value.0)),
                    constant(variant.value.1)
                )
                .unwrap();
            }
            writeln!(
                out,
                "static inline int {name}_valid({name} value) {{ switch(value) {{"
            )
            .unwrap();
            for variant in variants {
                writeln!(out, "case ({name}){}: return 1;", constant(variant.value.1)).unwrap();
            }
            out.push_str("default: return 0; } }\n");
        }
    }
    let mut pending: BTreeSet<_> = index
        .symbols
        .iter()
        .filter(|(_, s)| matches!(s.declaration.value.kind, ItemKind::Struct { .. }))
        .map(|(id, _)| id.clone())
        .collect();
    while !pending.is_empty() {
        let ready: Vec<_> = pending
            .iter()
            .filter(|id| {
                let mut dependencies = BTreeSet::new();
                for ty in checked.fields[*id].values() {
                    value_dependencies(ty, &mut dependencies);
                }
                dependencies.is_disjoint(&pending)
            })
            .cloned()
            .collect();
        if ready.is_empty() {
            return Err("cyclic by-value layout in ABI generation".into());
        }
        for id in ready {
            pending.remove(&id);
            let symbol = &index.symbols[&id];
            let ItemKind::Struct { fields, .. } = &symbol.declaration.value.kind else {
                unreachable!()
            };
            writeln!(out, "struct {} {{", identifier(&id)).unwrap();
            for field in fields {
                writeln!(
                    out,
                    "    {};",
                    declaration(
                        &checked.fields[&id][&field.value.name],
                        &identifier(&field.value.name)
                    )
                )
                .unwrap();
            }
            out.push_str("};\n");
        }
    }
    for (id, layout) in &checked.layouts {
        let name = identifier(id);
        writeln!(
            out,
            "FG_LAYOUT_ASSERT(sizeof({name}) == {}, \"size mismatch\");",
            layout.size
        )
        .unwrap();
        writeln!(
            out,
            "FG_LAYOUT_ASSERT(FG_LAYOUT_ALIGN({name}) == {}, \"alignment mismatch\");",
            layout.align
        )
        .unwrap();
        for (field, offset) in &layout.fields {
            writeln!(
                out,
                "FG_LAYOUT_ASSERT(offsetof({name}, {}) == {offset}, \"offset mismatch\");",
                identifier(field)
            )
            .unwrap();
        }
    }
    for (id, signature) in &checked.signatures {
        if signature
            .parameters
            .iter()
            .chain(signature.returns.iter())
            .any(|t| matches!(t, Ty::Array(..)))
        {
            return Err(format!(
                "`{id}` uses a direct array parameter/return; use an explicit C-layout struct wrapper to preserve by-value semantics"
            ));
        }
        let parameters = if signature.parameters.is_empty() {
            "void".into()
        } else {
            signature
                .parameters
                .iter()
                .enumerate()
                .map(|(i, t)| declaration(t, &format!("p{i}")))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let function = format!("{}({parameters})", identifier(id));
        let prototype = signature
            .returns
            .as_ref()
            .map_or_else(|| format!("void {function}"), |t| declaration(t, &function));
        writeln!(out, "{prototype};").unwrap();
    }
    out.push_str(
        "#ifdef __cplusplus\n}\n#endif\n#undef FG_LAYOUT_ASSERT\n#undef FG_LAYOUT_ALIGN\n",
    );
    Ok(Header {
        source: out,
        symbols,
    })
}

fn rust_type(ty: &Ty) -> String {
    match ty {
        Ty::Integer { signed, bits } => format!("{}{bits}", if *signed { "i" } else { "u" }),
        Ty::Bool => "u8".into(),
        Ty::Struct(id) | Ty::Enum(id) => identifier(id),
        Ty::Pointer(inner) => format!("*mut {}", rust_type(inner)),
        Ty::Array(inner, size) => format!("[{}; {size}]", rust_type(inner)),
    }
}
/// Generate repr(C) Rust bindings for the same native ABI as `generate`.
pub fn generate_rust(index: &Index, checked: &CheckedTypes) -> Result<String, String> {
    // Apply the same ABI exclusions as the C declarations before emitting anything.
    generate(index, checked)?;
    let mut out = String::from(
        "// Generated by Fingolfin. Wire bools/enums use integer representations.\n#![allow(non_camel_case_types, non_upper_case_globals)]\n#[cfg(not(all(target_os=\"linux\", target_arch=\"x86_64\", target_endian=\"little\")))]\ncompile_error!(\"Unsupported Fingolfin ABI target\");\n",
    );
    for (id, symbol) in &index.symbols {
        let name = identifier(id);
        match &symbol.declaration.value.kind {
            ItemKind::Struct { fields, .. } => {
                writeln!(
                    out,
                    "#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {name} {{"
                )
                .unwrap();
                for field in fields {
                    writeln!(
                        out,
                        "    pub {}: {},",
                        identifier(&field.value.name),
                        rust_type(&checked.fields[id][&field.value.name])
                    )
                    .unwrap();
                }
                out.push_str("}\n");
            }
            ItemKind::Enum { repr, variants, .. } => {
                let repr = crate::types::resolve_type(index, &symbol.module, repr)?;
                writeln!(out, "pub type {name} = {};", rust_type(&repr)).unwrap();
                for variant in variants {
                    writeln!(
                        out,
                        "pub const {}: {name} = ({}i128) as {name};",
                        identifier(&format!("{id}::{}", variant.value.0)),
                        variant.value.1
                    )
                    .unwrap();
                }
                writeln!(out, "pub fn {name}_valid(value: {name}) -> bool {{").unwrap();
                let checks = variants
                    .iter()
                    .map(|v| format!("value == {}", identifier(&format!("{id}::{}", v.value.0))))
                    .collect::<Vec<_>>()
                    .join(" || ");
                writeln!(out, "    {checks}\n}}").unwrap();
            }
            _ => {}
        }
    }
    for (id, layout) in &checked.layouts {
        let name = identifier(id);
        writeln!(
            out,
            "const _: () = assert!(core::mem::size_of::<{name}>() == {});",
            layout.size
        )
        .unwrap();
        writeln!(
            out,
            "const _: () = assert!(core::mem::align_of::<{name}>() == {});",
            layout.align
        )
        .unwrap();
        for (field, offset) in &layout.fields {
            writeln!(
                out,
                "const _: () = assert!(core::mem::offset_of!({name}, {}) == {offset});",
                identifier(field)
            )
            .unwrap();
        }
    }
    out.push_str("unsafe extern \"C\" {\n");
    for (id, signature) in &checked.signatures {
        let parameters = signature
            .parameters
            .iter()
            .enumerate()
            .map(|(i, t)| format!("p{i}: {}", rust_type(t)))
            .collect::<Vec<_>>()
            .join(", ");
        let returns = signature
            .returns
            .as_ref()
            .map_or(String::new(), |t| format!(" -> {}", rust_type(t)));
        writeln!(out, "    pub fn {}({parameters}){returns};", identifier(id)).unwrap();
    }
    out.push_str("}\n");
    Ok(out)
}
